package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

type tsv struct {
	name string
	buf  bytes.Buffer
}

func newTSV(name string, cols ...string) *tsv {
	t := &tsv{name: name}
	t.row(cols...)
	return t
}

func (t *tsv) row(cols ...string) {
	for i, c := range cols {
		c = strings.NewReplacer("\t", " ", "\n", " ").Replace(c)
		if i > 0 {
			t.buf.WriteByte('\t')
		}
		t.buf.WriteString(c)
	}
	t.buf.WriteByte('\n')
}

func itoa(n int) string { return fmt.Sprint(n) }

func loc(file string, line int) string { return fmt.Sprintf("%s:%d", file, line) }

func (inv *inventory) link(file string, line int) string {
	return fmt.Sprintf("[%s](%s/%s#L%d)", loc(file, line), inv.cfg.Link, file, line)
}

func (inv *inventory) fnLink(f *fnInfo) string {
	return fmt.Sprintf("`%s` %s", f.Display(), inv.link(f.File, f.Line))
}

func joinSorted(m map[string]bool) string { return strings.Join(sortedKeys(m), ", ") }

func md(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

func (inv *inventory) write(out string, elapsed time.Duration) error {
	var b bytes.Buffer
	var files []*tsv
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	cfg := inv.cfg
	top := cfg.Top
	fns := inv.realFns()

	clusters := inv.clusters(cfg.Cluster)
	loose := inv.clusters(cfg.ClusterLow)
	groups := inv.fieldGroups()
	mapFns, keySets := inv.mapFunctions()
	paramGroups := inv.paramGroups()
	sepRows, prefixRows := inv.stringMatches()
	grid, impl := inv.grid(fns)
	resp := inv.rules.Order
	long := 0
	lines := 0
	for _, f := range fns {
		lines += f.Lines
		if f.Lines >= cfg.Long {
			long++
		}
	}
	pkgSet := map[string]bool{}
	for _, f := range inv.files {
		pkgSet[f.Pkg] = true
	}

	// ---------------- header
	p("# Code inventory: %s\n\n", filepath.Base(cfg.Root))
	p("Generated by `code-inventory` on %s in %s. Observations and measured groupings only; nothing here is a plan or a recommendation.\n\n", time.Now().Format("2006-01-02"), elapsed.Round(time.Second))
	p("| | |\n|---|---|\n")
	p("| Path | `%s` |\n", cfg.Root)
	p("| Commit | %s |\n", md(inv.commit))
	p("| Packages | `%s` (non-test files under the path): %d packages, %d files |\n", strings.Join(cfg.Patterns, "` `"), len(pkgSet), len(inv.files))
	if len(inv.loadErrs) > 0 {
		p("| Load errors | %d (first: %s); type information is missing where they occur |\n", len(inv.loadErrs), md(inv.loadErrs[0]))
	}
	p("| Responsibility rules | %s (%d rules, %d responsibilities) |\n", md(strings.Join(inv.rules.Sources, " + ")), len(inv.rules.Rules), len(resp))
	p("| Thresholds | structs mapped: top %d by field count%s; clusters Jaccard >= %.2f and >= %.2f; pairs >= %.2f; long functions >= %d lines; tuples >= %d results, parameter lists >= %d; id separators %s |\n",
		cfg.Structs, namedNote(cfg.Named), cfg.Cluster, cfg.ClusterLow, cfg.Pair, cfg.Long, cfg.Results, cfg.Params, "`"+strings.Join(cfg.Seps, "` `")+"`")
	p("| Method | `go/packages` + `go/types` over the syntax trees; every claim comes from the rules and thresholds printed here |\n")
	p("\nEvery table is written in full as a TSV next to this file; the report shows the top %d rows. Re-run and diff the TSVs to see what changed.\n\n", top)

	// ---------------- summary
	p("## Summary\n\n| Measure | Value |\n|---|---|\n")
	p("| Functions and methods (lines in them) | %d (%d) |\n", len(fns), lines)
	p("| Functions of %d lines or more | %d |\n", cfg.Long, long)
	p("| Struct types | %d |\n", len(inv.structs))
	for _, t := range inv.targets {
		unread := 0
		for _, f := range inv.fields {
			if f.Struct == t.Label && len(f.Readers) == 0 {
				unread++
			}
		}
		nc, nl := 0, 0
		for _, c := range clusters {
			if c.Struct == t.Label {
				nc++
			}
		}
		for _, c := range loose {
			if c.Struct == t.Label {
				nl++
			}
		}
		p("| `%s`: fields (never read in scope); clusters at %.2f / %.2f | %d (%d); %d / %d |\n", t.Label, cfg.Cluster, cfg.ClusterLow, t.Fields, unread, nc, nl)
	}
	sup3 := 0
	for _, g := range groups {
		if len(g.Structs) >= 3 {
			sup3++
		}
	}
	p("| Field groups (2+ same-name same-type fields) shared by 3+ struct types | %d |\n", sup3)
	ifaceSites := 0
	for _, s := range inv.maps {
		if s.Iface {
			ifaceSites++
		}
	}
	p("| Constant-key map sites: interface-valued / other string-keyed / functions | %d / %d / %d |\n", ifaceSites, len(inv.maps)-ifaceSites, len(mapFns))
	p("| Functions returning %d+ values | %d |\n", cfg.Results, len(inv.results))
	rec := 0
	for _, g := range paramGroups {
		rec += len(g.Fns)
	}
	p("| Parameter lists of %d+ that recur with the same types: lists / functions | %d / %d |\n", cfg.Params, len(paramGroups), rec)
	joins, splits := 0, 0
	for _, s := range inv.strs {
		if s.Hit.Kind == "join" {
			joins++
		} else {
			splits++
		}
	}
	p("| Ids built in strings: join sites / split sites | %d / %d |\n", joins, splits)
	matched := 0
	for _, r := range prefixRows {
		if len(r.Join) > 0 && len(r.Split) > 0 {
			matched++
		}
	}
	p("| Literal prefixes (`\"word:\"`-style) both joined and split / seen | %d / %d |\n", matched, len(prefixRows))
	none, untagged := 0, 0
	for _, f := range fns {
		if f.Subject == "(none)" {
			none++
		}
		if len(f.Tags) == 0 {
			untagged++
		}
	}
	p("| Functions with no subject / with no responsibility (\"other\") | %d (%.0f%%) / %d (%.0f%%) |\n", none, pct(none, len(fns)), untagged, pct(untagged, len(fns)))
	multi := 0
	for _, r := range resp {
		if len(impl[r]) >= 2 {
			multi++
		}
	}
	p("| Responsibilities done directly (base or package-local) in 2+ subjects | %d of %d |\n", multi, len(resp))
	nt := inv.tests
	if nt.Struct != "" && nt.Err == "" {
		p("| `Test*` functions in `%s` reaching a constructor of `%s` | %d of %d (%.0f%%); %d call one directly |\n", nt.Pkg, nt.Struct, nt.Reach, nt.Tests, pct(nt.Reach, nt.Tests), nt.Direct)
	}
	p("\n")
	inv.writeLimits(p)

	// ---------------- 1a structs and fields
	p("## 1. Unnamed data\n\n### 1a. Largest structs and their fields\n\n")
	bySize := append([]*structRec(nil), inv.structs...)
	sort.SliceStable(bySize, func(i, j int) bool {
		if bySize[i].Fields != bySize[j].Fields {
			return bySize[i].Fields > bySize[j].Fields
		}
		return bySize[i].Label < bySize[j].Label
	})
	stt := newTSV("structs.tsv", "struct", "fields", "declared", "mapped")
	p("Struct types by field count (embedded fields count as one):\n\n| Struct | Fields | Declared | Mapped below |\n|---|---|---|---|\n")
	isTarget := map[*structRec]bool{}
	for _, t := range inv.targets {
		isTarget[t] = true
	}
	for i, s := range bySize {
		m := ""
		if isTarget[s] {
			m = "yes"
		}
		stt.row(s.Label, itoa(s.Fields), loc(s.File, s.Line), m)
		if i < top {
			p("| `%s` | %d | %s | %s |\n", s.Label, s.Fields, inv.link(s.File, s.Line), m)
		}
	}
	files = append(files, stt)
	p("\nFor each mapped struct, the functions in scope that read and write each field, from `go/types` selections. **Write** = assigned, incremented, address taken, ranged into, an element assigned (`s.f[k] = v`), or set in a composite literal. Everything else, including calling a method on it, is a **read**. Function literals count as their enclosing function.\n\n")
	ft := newTSV("fields.tsv", "struct", "field", "type", "declared", "readers", "writers", "reader_functions", "writer_functions")
	keys := sortedKeys(inv.fields)
	for _, k := range keys {
		f := inv.fields[k]
		ft.row(f.Struct, f.Field, f.Type, loc(f.File, f.Line), itoa(len(f.Readers)), itoa(len(f.Writers)), joinSorted(f.Readers), joinSorted(f.Writers))
	}
	files = append(files, ft)
	for _, t := range inv.targets {
		var fs []*fieldRec
		for _, k := range keys {
			if inv.fields[k].Struct == t.Label {
				fs = append(fs, inv.fields[k])
			}
		}
		var unread, one, wr []string
		for _, f := range fs {
			switch len(f.Readers) {
			case 0:
				unread = append(unread, "`"+f.Field+"`")
			case 1:
				one = append(one, "`"+f.Field+"`")
			}
			if len(f.Writers) >= 10 {
				wr = append(wr, fmt.Sprintf("`%s` (%d)", f.Field, len(f.Writers)))
			}
		}
		sort.SliceStable(fs, func(i, j int) bool { return len(fs[i].Readers) > len(fs[j].Readers) })
		p("**%s**: %d fields. Most read:\n\n| Field | Type | Readers | Writers | Declared |\n|---|---|---|---|---|\n", t.Label, len(fs))
		for i, f := range fs {
			if i == 10 {
				break
			}
			p("| `%s` | `%s` | %d | %d | %s |\n", f.Field, md(f.Type), len(f.Readers), len(f.Writers), inv.link(f.File, f.Line))
		}
		p("\n- Never read in scope (%d): %s\n", len(unread), strings.Join(unread, ", "))
		p("- Read by exactly one function (%d): %s\n", len(one), strings.Join(one, ", "))
		p("- Written by 10+ functions (%d): %s\n\n", len(wr), strings.Join(wr, ", "))
	}
	p("Full tables: `structs.tsv`, `fields.tsv`.\n\n")

	// ---------------- 1b clusters
	p("### 1b. Fields read together (clusters)\n\n")
	p("Method: each field's set of reader functions (1a). Similarity of two fields = Jaccard of their reader sets (|A∩B| / |A∪B|). Clusters are built bottom-up by complete linkage: the two clusters whose least similar pair is most similar are merged while that value is at least **%.2f**, so every pair in a cluster has Jaccard >= %.2f. A second pass uses %.2f. Ties break on sorted field names; fields never read take no part. Only clusters of 2+ fields are listed. `Shared readers` = functions that read every field of the cluster.\n\n", cfg.Cluster, cfg.Cluster, cfg.ClusterLow)
	ct := newTSV("field_clusters.tsv", "threshold", "struct", "size", "min_jaccard", "shared_readers", "fields", "shared_reader_functions")
	for _, set := range []struct {
		t  float64
		cs []cluster
	}{{cfg.Cluster, clusters}, {cfg.ClusterLow, loose}} {
		for _, c := range set.cs {
			ct.row(fmt.Sprintf("%.2f", set.t), c.Struct, itoa(len(c.Fields)), fmt.Sprintf("%.2f", c.Min), itoa(len(c.Shared)), strings.Join(c.Fields, " "), strings.Join(c.Shared, ", "))
		}
	}
	files = append(files, ct)
	pt := newTSV("field_pairs.tsv", "struct", "field_a", "field_b", "jaccard", "co_readers")
	for _, pr := range inv.fieldPairs() {
		pt.row(pr.Struct, pr.A, pr.B, fmt.Sprintf("%.2f", pr.J), itoa(pr.Co))
	}
	files = append(files, pt)
	for _, th := range []struct {
		t  float64
		cs []cluster
	}{{cfg.Cluster, clusters}, {cfg.ClusterLow, loose}} {
		for _, t := range inv.targets {
			var cs []cluster
			for _, c := range th.cs {
				if c.Struct == t.Label {
					cs = append(cs, c)
				}
			}
			sort.SliceStable(cs, func(i, j int) bool {
				if len(cs[i].Shared) != len(cs[j].Shared) {
					return len(cs[i].Shared) > len(cs[j].Shared)
				}
				return len(cs[i].Fields) > len(cs[j].Fields)
			})
			p("**%s**, Jaccard >= %.2f: %d clusters.\n\n", t.Label, th.t, len(cs))
			if len(cs) == 0 {
				continue
			}
			p("| Fields | Min J | Shared readers | Example readers |\n|---|---|---|---|\n")
			for i, c := range cs {
				if i == 12 {
					break
				}
				ex := c.Shared
				if len(ex) > 3 {
					ex = ex[:3]
				}
				p("| %s | %.2f | %d | %s |\n", "`"+strings.Join(c.Fields, "` `")+"`", c.Min, len(c.Shared), md(strings.Join(ex, ", ")))
			}
			p("\n")
		}
	}
	p("Full tables: `field_clusters.tsv`, `field_pairs.tsv` (pairs with Jaccard >= %.2f and 2+ shared readers).\n\n", cfg.Pair)

	// ---------------- 1c groups
	p("### 1c. Field groups repeated across struct types\n\n")
	p("Every named struct type in scope (%d) is a set of `name type` fields (types spelled with package names). A group is the intersection of two structs' sets when it has 2+ fields; its support is the number of struct types holding all of it. Listed by support, then size. Only exact name and type matches count.\n\n", len(inv.structs))
	gt := newTSV("field_groups.tsv", "structs", "size", "fields", "struct_types")
	for _, g := range groups {
		gt.row(itoa(len(g.Structs)), itoa(len(g.Fields)), strings.Join(g.Fields, "; "), strings.Join(g.Structs, ", "))
	}
	files = append(files, gt)
	p("| Structs | Fields | Example struct types |\n|---|---|---|\n")
	for i, g := range groups {
		if i == top {
			break
		}
		p("| %d | `%s` | %s |\n", len(g.Structs), md(strings.Join(g.Fields, "`, `")), trimList(g.Structs, 5))
	}
	if len(groups) == 0 {
		p("| 0 | | |\n")
	}
	p("\nFull table: `field_groups.tsv` (%d groups).\n\n", len(groups))

	// ---------------- 1d maps
	p("### 1d. Hand-decoded maps\n\n")
	p("A site is (a) an index `m[K]` where `m` is a map with a string key type and `K` is a constant (a literal or a named constant), or (b) a call that is passed an interface-valued string map (`map[string]any` and the like) and a constant string together (a decode helper such as `str(fields, \"title\")`). Interface-valued maps are counted apart from typed ones (`map[string]int` lookups are often plain tables). Grouped by function and by key set.\n\n")
	mt := newTSV("map_sites.tsv", "function", "site", "map_type", "interface_valued", "expr", "key", "use")
	for _, s := range inv.maps {
		iv := "no"
		if s.Iface {
			iv = "yes"
		}
		mt.row(s.Fn.ID, loc(s.File, s.Line), s.MapType, iv, s.Expr, fmt.Sprintf("%q", s.Key), s.Use)
	}
	files = append(files, mt)
	mft := newTSV("map_functions.tsv", "function", "where", "sites", "distinct_keys", "keys")
	for _, m := range mapFns {
		mft.row(m.Fn.ID, loc(m.Fn.File, m.Fn.Line), itoa(m.Sites), itoa(len(m.Keys)), strings.Join(quoteAll(m.Keys), " "))
	}
	files = append(files, mft)
	byType := map[string]int{}
	for _, s := range inv.maps {
		byType[s.MapType]++
	}
	var bt []string
	for i, k := range sortedByCount(byType) {
		if i == top {
			break
		}
		bt = append(bt, fmt.Sprintf("`%s` %d", k, byType[k]))
	}
	p("Sites by map type: %s.\n\n", md(strings.Join(bt, ", ")))
	p("Functions with the most distinct keys:\n\n| Function | Sites | Keys |\n|---|---|---|\n")
	for i, m := range mapFns {
		if i == top {
			break
		}
		p("| %s | %d | %s |\n", inv.fnLink(m.Fn), m.Sites, "`"+md(trimList(quoteAll(m.Keys), 12))+"`")
	}
	p("\nKey sets (2+ keys) decoded by more than one function:\n\n| Functions | Keys | Functions (first 4) |\n|---|---|---|\n")
	ksn := 0
	for _, ks := range keySets {
		if len(ks.Fns) < 2 {
			continue
		}
		ksn++
		if ksn > top {
			continue
		}
		p("| %d | `%s` | %s |\n", len(ks.Fns), md(strings.Join(quoteAll(ks.Keys), " ")), md(trimList(ks.Fns, 4)))
	}
	if ksn == 0 {
		p("| 0 | | |\n")
	}
	p("\nFull tables: `map_sites.tsv`, `map_functions.tsv`.\n\n")

	// ---------------- 1e tuples
	p("### 1e. Tuples\n\n")
	sort.SliceStable(inv.results, func(i, j int) bool { return inv.results[i].N > inv.results[j].N })
	rt := newTSV("tuple_results.tsv", "function", "where", "results", "types")
	for _, r := range inv.results {
		rt.row(r.Fn.ID, loc(r.Fn.File, r.Fn.Line), itoa(r.N), r.Types)
	}
	files = append(files, rt)
	resultGroups := map[string][]*fnInfo{}
	for _, r := range inv.results {
		resultGroups[r.Types] = append(resultGroups[r.Types], r.Fn)
	}
	p("Functions returning %d or more values: %d. Result tuples shared by 2+ functions:\n\n| Functions | Result types | Examples |\n|---|---|---|\n", cfg.Results, len(inv.results))
	for i, k := range sortedByLen(resultGroups) {
		if i == top || len(resultGroups[k]) < 2 {
			break
		}
		p("| %d | `(%s)` | %s |\n", len(resultGroups[k]), md(k), md(fnNames(resultGroups[k], 4)))
	}
	p("\nParameter lists of %d or more (receiver excluded) that recur with the same types in order: %d lists over %d functions.\n\n| Functions | Parameter types | Examples |\n|---|---|---|\n", cfg.Params, len(paramGroups), rec)
	pgt := newTSV("tuple_params.tsv", "functions", "params", "types", "function_list")
	for i, g := range paramGroups {
		pgt.row(itoa(len(g.Fns)), itoa(g.N), g.Types, fnNames(g.Fns, 0))
		if i < top {
			p("| %d | `(%s)` | %s |\n", len(g.Fns), md(g.Types), md(fnNames(g.Fns, 4)))
		}
	}
	files = append(files, pgt)
	p("\nFull tables: `tuple_results.tsv`, `tuple_params.tsv`.\n\n")

	// ---------------- 1f strings
	p("### 1f. Ids built in strings\n\n")
	p("Separators: %s. Joins: a `+` chain with a literal separator between two non-constant operands, or a literal prefix like `\"pane:\"` (lower-case word ending in a separator) before a non-constant; `fmt.Sprintf` formats with `%%v<sep>%%v` (numeric when both verbs are `d`, as in clock times) or starting `word<sep>%%v`; `strings.Join(x, sep)`. Splits: `strings.Split/SplitN/SplitAfter(N)/Cut/Index/LastIndex/IndexByte/LastIndexByte/IndexRune/Count` with the separator as argument; `strings.HasPrefix/TrimPrefix/CutPrefix` with a literal prefix. Joins and splits are matched by separator and, for prefixes, by the exact prefix.\n\n", "`"+strings.Join(cfg.Seps, "` `")+"`")
	st := newTSV("string_sites.tsv", "function", "site", "kind", "sep", "prefix", "form")
	for _, s := range inv.strs {
		st.row(s.Fn.ID, loc(s.File, s.Line), s.Hit.Kind, s.Hit.Sep, s.Hit.Prefix, s.Hit.Form)
	}
	files = append(files, st)
	p("| Separator | Join sites | Join functions | Split sites | Split functions | Functions that both join and split |\n|---|---|---|---|---|---|\n")
	for _, r := range sepRows {
		p("| `%s` | %d | %d | %d | %d | %d |\n", md(r.Sep), r.JoinSites, len(r.Join), r.SplitSites, len(r.Split), r.Both)
	}
	pt2 := newTSV("string_prefixes.tsv", "prefix", "join_functions", "split_functions", "joined_in", "split_in")
	for _, r := range prefixRows {
		pt2.row(r.Prefix, itoa(len(r.Join)), itoa(len(r.Split)), joinSorted(r.Join), joinSorted(r.Split))
	}
	files = append(files, pt2)
	p("\nLiteral prefixes, joined and split (most functions first):\n\n| Prefix | Joined in | Split in | Examples (join / split) |\n|---|---|---|---|\n")
	for i, r := range prefixRows {
		if i == top {
			break
		}
		p("| `%s` | %d | %d | %s / %s |\n", md(r.Prefix), len(r.Join), len(r.Split), md(trimList(shortAll(sortedKeys(r.Join)), 2)), md(trimList(shortAll(sortedKeys(r.Split)), 2)))
	}
	p("\nFull tables: `string_sites.tsv`, `string_prefixes.tsv`.\n\n")

	// ---------------- 2 responsibilities
	p("## 2. Responsibilities\n\n")
	p("Each function is tagged only from what it calls, the types it names, the constructs it uses and its own name, by the rule table below (%s). Package-level `var` initializers are left out. A function can carry several tags; one with none is **other**. Level: **base** = it calls a standard or third-party library (or uses a language construct) itself; **local** = a `named` rule matched something in the function's own package; **uses** = a `named` rule matched something in another package.\n\n", md(strings.Join(inv.rules.Sources, " + ")))
	p("| Responsibility | Level | Matched against | Pattern | With |\n|---|---|---|---|---|\n")
	for _, r := range inv.rules.Rules {
		w := ""
		if r.With != "" {
			w = "`" + md(r.With) + "`"
		}
		p("| %s | %s | %s | `%s` | %s |\n", r.Tag, r.Level, ruleKinds[r.Kind], md(r.Pattern), w)
	}
	p("\n**Subject** comes from the codebase's own type names: every exported named type declared in scope and every receiver type (%d names after splitting). Names are split into lower-case words (camelCase, `_`, `-`), plural `s` dropped. A function's subject is the first name found as a run of words in, in order: its own name, its receiver type, its file name, its package name (longest name first). The own name comes first because one large receiver often holds methods about many subjects. None found: `(none)`.\n\n", len(inv.vocab.names))
	src := map[string]int{}
	for _, f := range fns {
		src[f.SubjectFrom]++
	}
	p("Subject found from: function name %d, receiver %d, file %d, package %d, none %d.\n\n", src["function"], src["receiver"], src["file"], src["package"], src[""])

	gtsv := newTSV("responsibility_grid.tsv", "responsibility", "subject", "functions", "lines", "direct_functions", "direct_lines")
	rf := newTSV("responsibility_functions.tsv", "function", "where", "lines", "subject", "subject_from", "tags", "matched")
	for _, f := range fns {
		var tags, via []string
		for _, t := range sortedKeys(f.Tags) {
			tags = append(tags, t+"="+f.Tags[t])
			via = append(via, t+": "+joinSorted(f.Via[t]))
		}
		if len(tags) == 0 {
			tags = []string{"other"}
		}
		rf.row(f.ID, loc(f.File, f.Line), itoa(f.Lines), f.Subject, f.SubjectFrom, strings.Join(tags, " "), strings.Join(via, " | "))
	}
	files = append(files, rf)
	cols := append(append([]string{}, resp...), "other")
	subjTotals := map[string]int{}
	for _, f := range fns {
		subjTotals[f.Subject]++
	}
	subjects := sortedByCount(subjTotals)
	for _, r := range cols {
		for _, s := range subjects {
			if c := grid[r][s]; c.Funcs > 0 {
				gtsv.row(r, s, itoa(c.Funcs), itoa(c.Lines), itoa(c.DirectFuncs), itoa(c.DirectLines))
			}
		}
	}
	files = append(files, gtsv)
	p("Grid, functions / lines per cell (subjects with the most functions first, top %d rows; full grid in `responsibility_grid.tsv`):\n\n| Subject | Functions |", top)
	for _, r := range cols {
		p(" %s |", r)
	}
	p("\n|---|---|%s\n", strings.Repeat("---|", len(cols)))
	totals := map[string]cell{}
	for i, s := range subjects {
		for _, r := range cols {
			c := grid[r][s]
			t := totals[r]
			t.Funcs += c.Funcs
			t.Lines += c.Lines
			totals[r] = t
		}
		if i >= top {
			continue
		}
		p("| %s | %d |", s, subjTotals[s])
		for _, r := range cols {
			if c := grid[r][s]; c.Funcs == 0 {
				p(" |")
			} else {
				p(" %d / %d |", c.Funcs, c.Lines)
			}
		}
		p("\n")
	}
	p("| **all** | %d |", len(fns))
	for _, r := range cols {
		p(" %d / %d |", totals[r].Funcs, totals[r].Lines)
	}
	p("\n\n")

	p("### Same responsibility done directly in several subjects\n\n")
	p("For each responsibility, the subjects that have functions doing it **directly** (level base or local, not through another package), with the functions listed so each can be read. Full list: `responsibility_direct.tsv`.\n\n")
	dt := newTSV("responsibility_direct.tsv", "responsibility", "subject", "function", "where", "lines", "level", "matched")
	for _, r := range resp {
		subs := impl[r]
		names := sortedByLen(subs)
		p("**%s**: direct in %d subjects (%d functions).\n\n", r, len(names), countAll(subs))
		if len(names) > 0 {
			p("| Subject | Functions | Lines | Longest |\n|---|---|---|---|\n")
		}
		for i, s := range names {
			fs := subs[s]
			sort.SliceStable(fs, func(a, b int) bool { return fs[a].Lines > fs[b].Lines })
			n := 0
			for _, f := range fs {
				n += f.Lines
				dt.row(r, s, f.ID, loc(f.File, f.Line), itoa(f.Lines), f.Tags[r], joinSorted(f.Via[r]))
			}
			if i < 12 {
				var ex []string
				for j, f := range fs {
					if j == 3 {
						break
					}
					ex = append(ex, inv.fnLink(f))
				}
				p("| %s | %d | %d | %s |\n", s, len(fs), n, strings.Join(ex, "; "))
			}
		}
		if len(names) > 12 {
			p("\n%d more subjects in the TSV.\n", len(names)-12)
		}
		p("\n")
	}
	files = append(files, dt)

	// ---------------- 3 size
	p("## 3. Size\n\n")
	type pkgRec struct {
		Pkg, Dir                   string
		Files, Lines, Funcs, FLine int
	}
	pkgs := map[string]*pkgRec{}
	ft2 := newTSV("files.tsv", "package", "file", "lines", "functions", "function_lines")
	sort.Slice(inv.files, func(i, j int) bool { return inv.files[i].File < inv.files[j].File })
	for _, f := range inv.files {
		ft2.row(f.Pkg, f.File, itoa(f.Lines), itoa(f.Funcs), itoa(f.FuncLines))
		r := pkgs[f.Pkg]
		if r == nil {
			r = &pkgRec{Pkg: f.Pkg, Dir: filepath.Dir(f.File)}
			pkgs[f.Pkg] = r
		}
		r.Files++
		r.Lines += f.Lines
		r.Funcs += f.Funcs
		r.FLine += f.FuncLines
	}
	files = append(files, ft2)
	pkt := newTSV("packages.tsv", "package", "dir", "files", "lines", "functions", "function_lines")
	var pk []*pkgRec
	for _, k := range sortedKeys(pkgs) {
		v := pkgs[k]
		pkt.row(v.Pkg, v.Dir, itoa(v.Files), itoa(v.Lines), itoa(v.Funcs), itoa(v.FLine))
		pk = append(pk, v)
	}
	files = append(files, pkt)
	sort.SliceStable(pk, func(i, j int) bool { return pk[i].Lines > pk[j].Lines })
	p("Packages by non-test lines (top %d of %d; `packages.tsv`, per file `files.tsv`):\n\n| Package dir | Files | Lines | Functions |\n|---|---|---|---|\n", top, len(pk))
	for i, v := range pk {
		if i == top {
			break
		}
		p("| `%s` | %d | %d | %d |\n", v.Dir, v.Files, v.Lines, v.Funcs)
	}
	fl := append([]fileRec(nil), inv.files...)
	sort.SliceStable(fl, func(i, j int) bool { return fl[i].Lines > fl[j].Lines })
	p("\nLargest files:\n\n| File | Lines | Functions |\n|---|---|---|\n")
	for i, f := range fl {
		if i == top {
			break
		}
		p("| %s | %d | %d |\n", inv.link(f.File, 1), f.Lines, f.Funcs)
	}
	longs := append([]*fnInfo(nil), fns...)
	sort.SliceStable(longs, func(i, j int) bool { return longs[i].Lines > longs[j].Lines })
	lt := newTSV("long_functions.tsv", "function", "where", "lines", "subject", "tags")
	p("\nFunctions of %d lines or more (lines = last line - first line + 1 of the declaration): %d. Longest %d (all in `long_functions.tsv`):\n\n| Lines | Function | Subject | Tags |\n|---|---|---|---|\n", cfg.Long, long, top)
	for i, f := range longs {
		if f.Lines < cfg.Long {
			break
		}
		tags := strings.Join(sortedKeys(f.Tags), " ")
		lt.row(f.ID, loc(f.File, f.Line), itoa(f.Lines), f.Subject, tags)
		if i < top {
			p("| %d | %s | %s | %s |\n", f.Lines, inv.fnLink(f), f.Subject, tags)
		}
	}
	files = append(files, lt)

	p("\n### Tests that construct the largest struct with a constructor\n\n")
	if len(nt.Skipped) > 0 && !nt.NoCtor {
		p("Larger mapped structs with no `New*` constructor, skipped: `%s`.\n\n", strings.Join(nt.Skipped, "`, `"))
	}
	switch {
	case !cfg.Tests:
		p("Not measured (`--tests=false`).\n\n")
	case nt.Struct == "":
		p("Not measured (no struct mapped).\n\n")
	case nt.NoCtor:
		p("Not measured: no mapped struct has a package-level `New*` that returns it (`%s`).\n\n", strings.Join(nt.Skipped, "`, `"))
	case nt.Err != "":
		p("`%s`: not measured (%s).\n\n", nt.Struct, md(nt.Err))
	default:
		p("`%s` is loaded with its tests (internal and external). An edge from f to g when f's body names g (a call or a function value) inside that package or its `_test` package. A constructor is a package-level `New*` returning `%s` or a pointer to it: %s. A `Test*(t *testing.T)` reaches the struct when a constructor is reachable that way. Subtests count inside their parent; calls through interfaces or function fields are not followed, and tests in other packages are not counted, so this is a lower bound.\n\n", nt.Pkg, nt.Struct, "`"+strings.Join(nt.Constructors, "`, `")+"`")
		p("- `Test*` functions: %d; reaching a constructor: **%d (%.0f%%)**; calling one directly: %d.\n", nt.Tests, nt.Reach, pct(nt.Reach, nt.Tests), nt.Direct)
		p("- Test-file helpers returning the struct: %d.", len(nt.Helpers))
		ht := newTSV("test_helpers.tsv", "helper", "references", "where")
		if len(nt.Helpers) > 0 {
			p(" Most referenced:\n\n| Helper | References | Where |\n|---|---|---|\n")
		} else {
			p("\n")
		}
		for i, h := range nt.Helpers {
			ht.row(h.Name, itoa(h.Refs), loc(h.File, h.Line))
			if i < top {
				p("| `%s` | %d | %s |\n", h.Name, h.Refs, inv.link(h.File, h.Line))
			}
		}
		files = append(files, ht)
		p("\n")
	}

	p("## Run\n\n```sh\ncode-inventory %s --packages '%s' --structs %d%s%s --out %s\n```\n\nPhase timings: %s.\n",
		cfg.Root, strings.Join(cfg.Patterns, " "), cfg.Structs, repeatFlag("--struct", cfg.Named), repeatFlag("--rules", cfg.RuleFiles), cfg.Out, strings.Join(inv.timings, "; "))

	if err := os.WriteFile(filepath.Join(out, "report.md"), b.Bytes(), 0o644); err != nil {
		return err
	}
	for _, t := range files {
		if err := os.WriteFile(filepath.Join(out, t.name), t.buf.Bytes(), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func namedNote(named []string) string {
	if len(named) == 0 {
		return ""
	}
	return " plus `" + strings.Join(named, "`, `") + "`"
}

func repeatFlag(name string, vals []string) string {
	var s string
	for _, v := range vals {
		s += " " + name + " " + v
	}
	return s
}

func (inv *inventory) writeLimits(p func(string, ...any)) {
	p("### What the tool cannot see\n\n")
	for _, s := range []string{
		"Calls through interfaces, function-typed fields and values (handlers in registration tables, callbacks) are tagged only by the interface method's name and package; the concrete code behind them is not followed. Function literals count as part of the function that holds them.",
		"Reflection, templates, struct tags (JSON, SQL) and generated code that is not checked in.",
		"Test files (except the constructor reachability in section 3), files excluded by build tags in the default build, packages outside the patterns, and nested modules (`./...` stops at a nested `go.mod`).",
		"Meaning. Tags come from imports and names: a function that calls `regexp` to validate input is tagged parse; an undo stack whose types are not named *history*/*undo* is missed. Subjects come from names, so a function whose name, receiver, file and package hold no type name has subject `(none)`.",
		"Fields read through a copy (`r := s.r; r.X`) count against the copied struct only when it is mapped too; map and slice contents are not tracked.",
		"Strings: separators other than those listed, `path.Join`/`filepath.Join` (file paths, left out on purpose), and ids written with `fmt.Fprintf` into builders.",
		"Run time. Nothing is executed; test durations are not measured.",
	} {
		p("- %s\n", s)
	}
	p("\n")
}

func pct(a, b int) float64 {
	if b == 0 {
		return 0
	}
	return 100 * float64(a) / float64(b)
}

func trimList(xs []string, n int) string {
	if len(xs) <= n {
		return strings.Join(xs, ", ")
	}
	return strings.Join(xs[:n], ", ") + fmt.Sprintf(" +%d", len(xs)-n)
}

func shortAll(xs []string) []string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = "`" + shortFn(x) + "`"
	}
	return out
}

// shortFn turns a function id into "pkg.(Recv).Name".
func shortFn(id string) string {
	head := id
	if i := strings.IndexAny(head, "(@"); i >= 0 {
		head = head[:i]
	}
	if i := strings.LastIndex(head, "/"); i >= 0 {
		return id[i+1:]
	}
	return id
}

func fnNames(fs []*fnInfo, n int) string {
	var xs []string
	for _, f := range fs {
		xs = append(xs, shortFn(f.ID))
	}
	sort.Strings(xs)
	if n == 0 {
		return strings.Join(xs, ", ")
	}
	return trimList(xs, n)
}

func sortedByCount(m map[string]int) []string {
	ks := sortedKeys(m)
	sort.SliceStable(ks, func(i, j int) bool { return m[ks[i]] > m[ks[j]] })
	return ks
}

func sortedByLen[V any](m map[string][]V) []string {
	ks := sortedKeys(m)
	sort.SliceStable(ks, func(i, j int) bool { return len(m[ks[i]]) > len(m[ks[j]]) })
	return ks
}

func countAll(m map[string][]*fnInfo) int {
	n := 0
	for _, v := range m {
		n += len(v)
	}
	return n
}

func quoteAll(xs []string) []string {
	out := make([]string, len(xs))
	for i, x := range xs {
		out[i] = fmt.Sprintf("%q", x)
	}
	return out
}
